#include "WatchFaceHorizon.h"

#include <cstdio>

using namespace Pinetime::Applications::Screens;

extern lv_font_t jetbrains_mono_bold_20;
extern lv_font_t jetbrains_mono_42;

namespace {
  constexpr const char* timeFont = "/fonts/horizon_time.bin";
  constexpr const char* dayFont = "/fonts/horizon_day.bin";
  constexpr const char* smallFont = "/fonts/horizon_small.bin";
  constexpr const char* domeImage = "/images/horizon_dome.bin";
  constexpr const char* sunImage = "/images/horizon_sun.bin";
  constexpr const char* moonImage = "/images/horizon_moon.bin";

  const lv_color_t sky = lv_color_hex(0x0a1633);
  const lv_color_t dateColour = lv_color_hex(0x9fb4e6);
  const lv_color_t locationColour = lv_color_hex(0xd2e0ff);

  constexpr lv_coord_t domeTop = 156;
  constexpr lv_coord_t sunSize = 18;
  constexpr lv_coord_t moonSize = 16;

  // Points along the dotted arc from its sunrise end (0) to its sunset end (24).
  // generated by tools/make_images.py: dome top y = 156
  constexpr lv_point_t sunPath[25] = {{17, 240},  {23, 232},  {30, 225},  {37, 218},  {45, 212},  {53, 207},  {62, 202},
                                      {71, 198},  {80, 194},  {90, 192},  {100, 190}, {110, 188}, {120, 188}, {130, 188},
                                      {140, 190}, {150, 192}, {160, 194}, {169, 198}, {178, 202}, {187, 207}, {195, 212},
                                      {203, 218}, {210, 225}, {217, 232}, {223, 240}};
  constexpr int pathSteps = 24;

  constexpr int16_t defaultSunrise = 6 * 60;
  constexpr int16_t defaultSunset = 18 * 60;
  constexpr int minutesPerDay = 24 * 60;

  bool FileExists(Pinetime::Controllers::FS& fs, const char* path) {
    lfs_file f = {};
    if (fs.FileOpen(&f, path, LFS_O_RDONLY) < 0) {
      return false;
    }
    fs.FileClose(&f);
    return true;
  }

  lv_font_t* LoadFont(Pinetime::Controllers::FS& fs, const char* path) {
    if (!FileExists(fs, path)) {
      return nullptr;
    }
    char lvPath[48];
    snprintf(lvPath, sizeof(lvPath), "F:%s", path);
    return lv_font_load(lvPath);
  }

  lv_obj_t* Label(const lv_font_t* font, lv_color_t colour) {
    lv_obj_t* l = lv_label_create(lv_scr_act(), nullptr);
    lv_obj_set_style_local_text_font(l, LV_LABEL_PART_MAIN, LV_STATE_DEFAULT, font);
    lv_obj_set_style_local_text_color(l, LV_LABEL_PART_MAIN, LV_STATE_DEFAULT, colour);
    return l;
  }

  lv_obj_t* Image(const char* path, lv_coord_t x, lv_coord_t y) {
    char lvPath[48];
    snprintf(lvPath, sizeof(lvPath), "F:%s", path);
    lv_obj_t* img = lv_img_create(lv_scr_act(), nullptr);
    lv_img_set_src(img, lvPath); // LVGL copies the path
    lv_obj_set_pos(img, x, y);
    return img;
  }

  // Position along the arc for progress/total (0 = sunrise end, total = sunset end), interpolated.
  lv_point_t PathPoint(int progress, int total) {
    if (total <= 0) {
      return sunPath[pathSteps / 2];
    }
    progress = progress < 0 ? 0 : (progress > total ? total : progress);
    const int scaled = progress * pathSteps * 16 / total; // 1/16 steps
    const int i = scaled / 16;
    const int frac = scaled % 16;
    if (i >= pathSteps) {
      return sunPath[pathSteps];
    }
    const lv_point_t a = sunPath[i];
    const lv_point_t b = sunPath[i + 1];
    return {static_cast<lv_coord_t>(a.x + (b.x - a.x) * frac / 16), static_cast<lv_coord_t>(a.y + (b.y - a.y) * frac / 16)};
  }
}

bool WatchFaceHorizon::IsAvailable(Pinetime::Controllers::FS& filesystem) {
  for (const char* path : {timeFont, dayFont, smallFont, domeImage, sunImage, moonImage}) {
    if (!FileExists(filesystem, path)) {
      return false;
    }
  }
  return true;
}

WatchFaceHorizon::WatchFaceHorizon(Controllers::DateTime& dateTime,
                                   Controllers::Settings& settings,
                                   Controllers::FS& filesystem,
                                   Controllers::SimpleWeatherService* weather)
  : dateTime {dateTime}, settings {settings}, weather {weather} {
  fontTime = LoadFont(filesystem, timeFont);
  fontDay = LoadFont(filesystem, dayFont);
  fontSmall = LoadFont(filesystem, smallFont);
  const lv_font_t* small = fontSmall != nullptr ? fontSmall : &jetbrains_mono_bold_20;

  lv_obj_t* background = lv_obj_create(lv_scr_act(), nullptr);
  lv_obj_set_size(background, LV_HOR_RES, LV_VER_RES);
  lv_obj_set_style_local_bg_color(background, LV_OBJ_PART_MAIN, LV_STATE_DEFAULT, sky);
  lv_obj_set_style_local_radius(background, LV_OBJ_PART_MAIN, LV_STATE_DEFAULT, 0);
  lv_obj_set_style_local_border_width(background, LV_OBJ_PART_MAIN, LV_STATE_DEFAULT, 0);

  date = Label(small, dateColour);
  weekday = Label(fontDay != nullptr ? fontDay : &jetbrains_mono_bold_20, LV_COLOR_WHITE);
  time = Label(fontTime != nullptr ? fontTime : &jetbrains_mono_42, LV_COLOR_WHITE);

  Image(domeImage, 0, domeTop);
  sun = Image(sunImage, 0, 0);
  moon = Image(moonImage, 0, 0);

  temperature = Label(small, LV_COLOR_WHITE);
  location = Label(small, locationColour);
  lv_label_set_long_mode(location, LV_LABEL_LONG_DOT);
  lv_obj_set_width(location, 200);
  lv_label_set_align(location, LV_LABEL_ALIGN_CENTER);

  refreshTask = lv_task_create(RefreshTaskCallback, 1000, LV_TASK_PRIO_MID, this);
  UpdateWeather();
  Refresh();
}

WatchFaceHorizon::~WatchFaceHorizon() {
  lv_task_del(refreshTask);
  lv_obj_clean(lv_scr_act());
  for (lv_font_t* f : {fontTime, fontDay, fontSmall}) {
    if (f != nullptr) {
      lv_font_free(f);
    }
  }
}

void WatchFaceHorizon::Refresh() {
  currentWeather = weather != nullptr ? weather->Current() : std::nullopt;
  const bool weatherChanged = currentWeather.IsUpdated();
  if (weatherChanged) {
    UpdateWeather();
  }
  currentMinute = std::chrono::time_point_cast<std::chrono::minutes>(dateTime.CurrentDateTime());
  if (currentMinute.IsUpdated()) {
    UpdateTime();
    UpdateSky();
  } else if (weatherChanged) {
    UpdateSky(); // new sunrise / sunset
  }
}

void WatchFaceHorizon::UpdateTime() {
  uint8_t hours = dateTime.Hours();
  if (settings.GetClockType() == Controllers::Settings::ClockType::H12) {
    const char* suffix = hours < 12 ? "AM" : "PM";
    hours = hours % 12 == 0 ? 12 : hours % 12;
    lv_label_set_text_fmt(time, "%d:%02d %s", hours, dateTime.Minutes(), suffix);
  } else {
    lv_label_set_text_fmt(time, "%02d:%02d", hours, dateTime.Minutes());
  }
  lv_obj_align(time, nullptr, LV_ALIGN_IN_TOP_MID, 0, 78);

  lv_label_set_text_fmt(date, "%d %s %d", dateTime.Day(), dateTime.MonthShortToString(), dateTime.Year());
  lv_obj_align(date, nullptr, LV_ALIGN_IN_TOP_MID, 0, 16);
  lv_label_set_text(weekday, Controllers::DateTime::DayOfWeekToStringLow(dateTime.DayOfWeek()));
  lv_obj_align(weekday, nullptr, LV_ALIGN_IN_TOP_MID, 0, 36);
}

void WatchFaceHorizon::UpdateWeather() {
  const auto& w = currentWeather.Get();
  if (!w.has_value()) {
    lv_label_set_text_static(temperature, "");
    lv_label_set_text_static(location, "No weather data");
  } else {
    const bool imperial = settings.GetWeatherFormat() == Controllers::Settings::WeatherFormat::Imperial;
    auto degrees = [imperial](const Controllers::SimpleWeatherService::Temperature& t) {
      return static_cast<int>(imperial ? t.Fahrenheit() : t.Celsius());
    };
    lv_label_set_text_fmt(temperature,
                          "%d\xC2\xB0   H %d\xC2\xB0  L %d\xC2\xB0",
                          degrees(w->temperature),
                          degrees(w->maxTemperature),
                          degrees(w->minTemperature));
    lv_label_set_text(location, w->location.data());
  }
  lv_obj_align(temperature, nullptr, LV_ALIGN_IN_TOP_MID, 0, 202);
  lv_obj_align(location, nullptr, LV_ALIGN_IN_TOP_MID, 0, 221);
}

void WatchFaceHorizon::UpdateSky() {
  int16_t sunrise = defaultSunrise;
  int16_t sunset = defaultSunset;
  bool polarDay = false;
  bool polarNight = false;
  if (const auto& w = currentWeather.Get(); w.has_value()) {
    polarNight = w->sunrise == -2;
    polarDay = w->sunset == -2 && w->sunrise >= 0;
    if (w->sunrise >= 0 && w->sunset > w->sunrise) {
      sunrise = w->sunrise;
      sunset = w->sunset;
    }
  }

  const int now = dateTime.Hours() * 60 + dateTime.Minutes();
  const bool day = polarDay || (!polarNight && now >= sunrise && now < sunset);
  lv_point_t p;
  if (polarDay || polarNight) {
    p = sunPath[pathSteps / 2];
  } else if (day) {
    p = PathPoint(now - sunrise, sunset - sunrise);
  } else {
    const int nightLength = minutesPerDay - sunset + sunrise;
    const int elapsed = now >= sunset ? now - sunset : now + minutesPerDay - sunset;
    p = PathPoint(elapsed, nightLength);
  }

  lv_obj_set_hidden(sun, !day);
  lv_obj_set_hidden(moon, day);
  if (day) {
    lv_obj_set_pos(sun, p.x - sunSize / 2, p.y - sunSize / 2);
  } else {
    lv_obj_set_pos(moon, p.x - moonSize / 2, p.y - moonSize / 2);
  }
}
